export const SchedultApi = {
  getAll: async (param) => {
    const response = await api.get("/timetable/index", param);
    return response.data;
  },
  getShow: async (id) => {
    const response = await api.get(`/timetable/show/${id}`);
    return response.data;
  },
  addNew: async (NewSchedult) => {
    const response = await api.post("/timetable/store", NewSchedult);
    return response.data;
  },
  update: async (UpdateSchedult, id) => {
    const response = await api.put(`/timetable/store/${id}`, UpdateSchedult);
    return response.data;
  },
  delete: async (id) => {
    const response = await api.delete(`/timetable/destroy/${id}`);
    return response.data;
  },
};
